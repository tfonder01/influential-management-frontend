import { expect, test } from "@playwright/test"

test("demo status filters retain disabled and invited mutations", async ({ page }) => {
  await page.goto("/admin/users")
  const filter = page.getByLabel("Status", { exact: true })
  await expect(filter).toHaveValue("current")
  await expect(page.locator("article").first()).toBeVisible()
  const initial = await page.locator("article").count()
  const director = page.locator("article").filter({ hasText: "Rachel Torres" })
  await director.getByRole("button", { name: "Disable", exact: true }).click()
  await page.getByRole("dialog").getByRole("button", { name: "Disable user", exact: true }).click()
  await expect(page.locator("article")).toHaveCount(initial - 1)
  await filter.selectOption("disabled"); await expect(page.locator("article")).toHaveCount(1)
  await filter.selectOption("all"); await expect(page.locator("article")).toHaveCount(initial)
  await filter.selectOption("disabled")
  await page.getByRole("button", { name: "Reactivate", exact: true }).click()
  await page.getByRole("dialog").getByRole("button", { name: "Reactivate user", exact: true }).click()
  await expect(page.getByText("No disabled users found", { exact: true })).toBeVisible()
  await filter.selectOption("current"); await expect(page.locator("article")).toHaveCount(initial)
  await page.getByRole("button", { name: "Invite user", exact: true }).click()
  const invite = page.getByRole("dialog", { name: "Invite user" })
  await invite.getByLabel("Full name").fill("Demo Pending")
  await invite.getByLabel("Email", { exact: true }).fill("demo.pending@example.test")
  await invite.getByRole("combobox").selectOption("OWNER")
  await invite.getByRole("button", { name: "Send invitation" }).click()
  await page.getByRole("button", { name: "Done", exact: true }).click()
  await filter.selectOption("invited"); await expect(page.locator("article")).toHaveCount(1)
  await page.getByRole("button", { name: "Disable", exact: true }).click()
  await page.getByRole("dialog").getByRole("button", { name: "Disable user", exact: true }).click()
  await filter.selectOption("disabled")
  await page.getByRole("button", { name: "Reactivate", exact: true }).click()
  await page.getByRole("dialog").getByRole("button", { name: "Reactivate user", exact: true }).click()
  await filter.selectOption("invited"); await expect(page.locator("article")).toHaveCount(1)
  await expect(page.getByText("Demo Pending", { exact: true })).toBeVisible()
})
