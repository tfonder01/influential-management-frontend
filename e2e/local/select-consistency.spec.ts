  expect(state.supply[0]).toMatchObject({ locationId: "one", category: "SUPPLIES", priority: "MEDIUM", area: "Preschool - 1 A", classroomAgeGroup: "PRESCHOOL", quantity: 1 })
  await expect(dialog).not.toBeVisible()
