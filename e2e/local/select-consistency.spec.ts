for (const width of [390, 430, 768, 1440]) test(`long labels, dialog layering, scrolling and popup collision at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 700 }); await setup(page, { locationName: longName })
  const dialog = await openSupply(page), location = dialog.getByLabel("Location", { exact: true })
  await expect(location).toContainText(longName)
  expect(await location.evaluate((element) => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  await location.click(); await viewportContainsPopup(page)
  await page.screenshot({ path: `test-results/select-long-${width}.png` })
  await page.getByRole("option", { name: "Location two", exact: true }).click()
  await expect(location).toContainText("Location two")
  const priority = dialog.getByLabel("Priority", { exact: true })
  await priority.evaluate((element: HTMLElement) => Object.assign(element.style, { position: "fixed", bottom: "8px", right: "8px", width: "180px" }))
  await priority.click(); await viewportContainsPopup(page)
  await expect(page.locator('[data-slot="select-content"][data-open]')).toHaveAttribute("data-side", "top")
  await page.keyboard.press("Escape")
  await priority.evaluate((element) => element.removeAttribute("style"))
  await dialog.getByLabel("Item / Request Title").fill("Scrolled field remains usable")
  await expect(page.getByRole("listbox")).toHaveCount(0)
  await location.scrollIntoViewIfNeeded()
  await page.screenshot({ path: `test-results/select-supply-${width}.png` })
})

test("Maintenance legacy assignment stays disabled and can be replaced and cleared", async ({ page }) => {
  const { base } = await setup(page)
  base.showHistory = true
  Object.assign(base.record, { assignedTo: "Historical vendor", assignedUserId: null })
  await page.goto("/maintenance/history")
  const assigned = page.getByLabel("Assigned To")
  await expect(assigned).toContainText("Historical vendor (legacy assignment)")
  await assigned.click()
  const legacy = page.getByRole("option", { name: "Historical vendor (legacy assignment)", exact: true })
  await expect(legacy).toHaveAttribute("aria-disabled", "true")
  await page.keyboard.press("Home"); await page.keyboard.press("ArrowDown")
  // Base UI intentionally exposes disabled options to keyboard focus, but never selects them.
  await expect(legacy).toBeFocused(); await page.keyboard.press("Enter")
  await expect(assigned).toContainText("Historical vendor (legacy assignment)")
  expect(base.payloads).toHaveLength(0)
  await page.getByRole("option", { name: `${longName} — Director`, exact: true }).click()
  await page.getByRole("button", { name: "Save repair details", exact: true }).click()
  await expect.poll(() => base.payloads.length).toBe(1)
  expect(base.payloads[0]).toMatchObject({ assignedUserId: "assignee" })
  await selectPopupOption(assigned, "Not assigned")
  await page.getByRole("button", { name: "Save repair details", exact: true }).click()
  await expect.poll(() => base.payloads.length).toBe(2)
  expect(base.payloads[1]).toMatchObject({ assignedUserId: null })
})

